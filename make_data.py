#!/usr/bin/env python3
"""Usage: python make_data.py your-file.csv
Reads your CSV (comma-separated, UTF-8) and writes:
  data.js                  -> rows shown in the "Preview the Dataset" table
  assets/sample-data.csv   -> the demo file visitors can download (same columns/format as your CSV)
Edit COLS to change which columns are shown/downloaded."""
import csv, json, sys
COLS = ["link","title","type","published_date","received_date","accepted_date","country","keywords","doi","authors","affiliations","source_page"]
raw = open(sys.argv[1], "rb").read()
try: txt = raw.decode("utf-8-sig")
except UnicodeDecodeError: txt = raw.decode("cp1252", errors="replace")
rd = csv.DictReader(txt.splitlines(True), delimiter="\t" if txt.split("\n",1)[0].count("\t") > 3 else ",")
rows = [[r.get(c, "") for c in COLS] for r in rd]
with open("assets/sample-data.csv", "w", encoding="utf-8-sig", newline="") as f:
    w = csv.writer(f); w.writerow(COLS); w.writerows(rows)
open("data.js", "w", encoding="utf-8").write("// Generated by make_data.py from your CSV.\nwindow.SAMPLE_DATA = " + json.dumps(rows, ensure_ascii=False, separators=(",", ":")) + ";\n")
print(len(rows), "rows")
